"""
Builds `submission_bot.py`: one self-contained file for the Deep-ML contest notebook.

It inlines (in order) the preflop tables, the hand evaluator, the ICM engine, the
ApexBot core and the SDK adapter (`bots/sdk_adapter.py`), and ends by binding the
core (ApexPlus) to `MyBot`. The only external import is the platform's own
`from pokerbot_sdk import Bot, Action`.

Paste the whole file into the FIRST notebook cell (it starts with a __future__
import, which must be the first statement), then use a second cell for
`play_local(MyBot(), tables=20)` (play_local lines are stripped on submit).

    python submission_builder.py
"""

from __future__ import annotations

import re
from pathlib import Path

TAIL = '''
# ==============================================================================
# ENTRY POINT
# ==============================================================================
# Core engine used by MyBot. Tuned parameter overrides (from tools/tune.py) go here.
class ContestCore(ApexPlus):
{overrides}

MyBot.core_factory = ContestCore

# Freeze everything allocated at import (lookup tables) so the cyclic GC never walks
# it during a 1 ms decision.
gc.collect()
gc.freeze()
'''


def strip_internal_imports(src: str) -> str:
    lines = []
    skip_multiline = False
    for line in src.splitlines():
        if skip_multiline:
            if ")" in line:
                skip_multiline = False
            continue
        if line.startswith("from __future__ import"):
            continue
        if line.startswith("from poker_engine.") or line.startswith("from bots."):
            if "(" in line and ")" not in line:
                skip_multiline = True
            continue
        lines.append(line)
    return "\n".join(lines)


def build_submission_file(output_path: str = "submission_bot.py", overrides: dict | None = None,
                          shake: bool = True) -> Path:
    root = Path(__file__).parent
    parts = {
        "PREFLOP TABLES": root / "poker_engine" / "preflop_tables.py",
        "HAND EVALUATOR & RANGE EQUITY": root / "poker_engine" / "evaluator.py",
        "ICM & BUBBLE FACTOR": root / "poker_engine" / "icm.py",
        "APEXBOT CORE": root / "bots" / "apex_bot.py",
        "MULTIWAY PREFLOP EQUITY TABLE": root / "poker_engine" / "preflop_multiway.py",
        "VECTORIZED RANGE ENGINE (numpy)": root / "poker_engine" / "range_engine.py",
        "OPPONENT FINGERPRINTING": root / "bots" / "fp_core.py",
        "FINGERPRINT DATA (generated from replays)": root / "bots" / "fingerprints.py",
        "BET-SIZE TELL DATA (generated from replays)": root / "bots" / "tells.py",
        "APEXPLUS: EXACT HEADS-UP RIVER PROFILE": root / "bots" / "apex_plus.py",
        "DEEP-ML SDK ADAPTER (MyBot)": root / "bots" / "sdk_adapter.py",
    }
    if overrides is None:
        overrides = load_tuned_overrides(root)
    body = "\n".join(f"    {k} = {v!r}" for k, v in sorted(overrides.items())) or "    pass"

    chunks = [
        "from __future__ import annotations",
        '"""\nDeep-ML No-Limit Hold\'em Pokerbot - single-file submission (auto-generated by\n'
        'submission_builder.py; edit the sources and rebuild instead of editing this file).\n"""',
        "import gc\nimport math\nimport random\nimport time\n"
        "from time import perf_counter_ns as _perf_ns\n"
        "from time import perf_counter_ns as _perf_counter_ns\n"
        "import numpy as np\n"
        "from typing import Any, Dict, List, Optional, Sequence, Tuple",
    ]
    for title, path in parts.items():
        chunks.append(f"# {'=' * 78}\n# {title}\n# {'=' * 78}")
        chunks.append(strip_internal_imports(path.read_text(encoding="utf-8")))
    chunks.append(TAIL.replace("{overrides}", body).strip())
    combined = "\n\n".join(chunks) + "\n"
    if shake:
        # drop functions / classes / constants nothing references (e.g. simulator-only helpers);
        # tools/equiv.py proved this decision-identical on the round-3 build
        import sys as _sys
        _sys.path.insert(0, str(root))
        from tools.treeshake import shake as _shake
        combined, removed = _shake(combined)
        print(f"Tree-shaken: removed {len(removed)} unreferenced definitions")
    compile(combined, output_path, "exec")

    out = root / output_path
    out.write_text(combined, encoding="utf-8")
    print(f"Built {out} ({len(combined):,} bytes, {len(combined.splitlines())} lines), "
          f"overrides: {overrides or 'none'}")
    return out


def load_tuned_overrides(root: Path) -> dict:
    """Reads the P_* overrides from bots/tuned_params.py if present."""
    f = root / "bots" / "tuned_params.py"
    if not f.exists():
        return {}
    ns: dict = {}
    exec(f.read_text(encoding="utf-8"), ns)
    return {k: v for k, v in ns.get("TUNED", {}).items() if re.match(r"^P_[A-Z0-9_]+$", k)}


if __name__ == "__main__":
    build_submission_file()
