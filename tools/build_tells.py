"""Bet-size tells from replays -> bots/tells.py.
For every postflop FIRST bet (not a raise) in a heads-up pot: bettor's hand-strength percentile on the current board
(vs all hands, tools/fit_r1_models2.strength) by bot, street and bet/pot bucket, as 10-bin histograms.
python tools/build_tells.py data/r4 [first_n_games]"""
import glob, json, sys
from collections import defaultdict
sys.path.insert(0, ".")
from tools.fit_r1_models2 import strength, parse_card  # noqa: E402

EDGES = (0.36, 0.42, 0.52, 0.62, 0.80, 1.20)   # bet / pot buckets 0..6 (6 = >= 1.2 incl. big all-ins)


def bucket(r):
    for i, e in enumerate(EDGES):
        if r < e:
            return i
    return len(EDGES)


def collect(files):
    H = defaultdict(lambda: [0] * 10)     # (bot, street, bucket) -> histogram ; bot "_pop" = everyone
    for f in files:
        g = json.load(open(f, encoding="utf-8"))["game"]
        nm = [p["name"].replace(" (copy)", "") for p in g["players"]]
        for h in g["hands"]:
            board_all = [parse_card(c) for c in h.get("board", [])]
            holes = h["hole"]
            folded = set(); prev = 0
            for st in range(4):
                acts = [a for a in h["a"] if a[0] == st]
                com = defaultdict(int)
                in_hand = {a[1] for a in h["a"] if a[0] == st}
                bet_seen = False
                for a in acts:
                    s, c, amt = a[1], a[2], a[3]
                    if st > 0 and not bet_seen and c in "BA" and amt > 0 and len(in_hand - folded) == 2 and holes[s]:
                        board = board_all[: {1: 3, 2: 4, 3: 5}[st]]
                        if len(board) == {1: 3, 2: 4, 3: 5}[st]:
                            sg = strength(tuple(parse_card(x) for x in holes[s]), board)
                            b = bucket(amt / max(1, prev))
                            d = min(9, int(sg * 10))
                            for who in (nm[s], "_pop"):
                                H[(who, st, b)][d] += 1
                    if c in "BRA":
                        bet_seen = True
                    if c == "F":
                        folded.add(s)
                    if c in "CBRAb" and amt:
                        com[s] = max(com[s], amt)
                prev += sum(com.values())
    return H


if __name__ == "__main__":
    files = sorted(glob.glob(sys.argv[1] + "/*.json"))
    if len(sys.argv) > 2:
        files = files[: int(sys.argv[2])]
    H = collect(files)
    out = {}
    for (who, st, b), hist in H.items():
        out.setdefault(who, {}).setdefault(str(st), {})[str(b)] = hist
    with open("bots/tells.py", "w", encoding="utf-8") as fo:
        fo.write('"""Generated by tools/build_tells.py from %s: bettor hand-strength histograms (10 bins of the board\n'
                 'percentile) per bot / street / bet-to-pot bucket, first bets in heads-up pots."""\n\n' % sys.argv[1])
        fo.write("TELL_EDGES = %r\n\n" % (EDGES,))
        fo.write("TELLS = " + json.dumps(out, sort_keys=True) + "\n")
    for who in sorted(out):
        row = []
        for b in range(7):
            hs = [out[who].get(str(st), {}).get(str(b), [0] * 10) for st in (1, 2, 3)]
            n = sum(sum(x) for x in hs)
            m = sum(sum(x[d] * (d + 0.5) / 10 for d in range(10)) for x in hs) / max(1, n)
            row.append(f"{m:.2f}(n{n})")
        print(f"{who[:15]:<16}", " ".join(f"{r:>12}" for r in row))
    print("buckets: <.36 .36-.42 .42-.52 .52-.62 .62-.80 .80-1.2 >=1.2")
