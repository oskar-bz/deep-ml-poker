"""Regenerate bots/fingerprints.py (signatures + measured profiles) from a replay folder.

python tools/rebuild_fp.py data/r4 [build_for_profiles] [max_games]
"""
import glob, json, sys
sys.path.insert(0, ".")
from tools.build_profiles import build_signatures, build_profiles, FINALISTS  # noqa: E402

folder = sys.argv[1]
build = sys.argv[2] if len(sys.argv) > 2 else "contest/round4_submission_bot.py"
n = int(sys.argv[3]) if len(sys.argv) > 3 else 100000
files = sorted(glob.glob(folder + "/*.json"))[:n]
sig = build_signatures(files)
agg, errs = build_profiles(files, build)
print("games", len(files), "feed errors:", len(errs))
pairs = [("faced_steal", "folded_steal"), ("faced_steal", "threebet_count"), ("faced_3bet", "folded_3bet"),
         ("faced_3bet", "fourbet_count"), ("faced_jam", "called_jam"), ("post_faced_bet", "post_folded_bet"),
         ("vu_faced", "vu_3b"), ("f4_n", "f4_fold"), ("check_faced_bet", "check_folded_bet"), ("faced_xr", "folded_xr")]
prof = {}
for b in FINALISTS:
    a = agg[b]; prof[b] = {}; row = []
    for n_k, k_k in pairs:
        nn = a[n_k]; k = a[k_k]
        prof[b][k_k] = [round(k / nn, 4) if nn else None, int(nn)]
        row.append(f"{k_k}={k/max(1,nn):.2f}(n{nn})")
    print(f"{b:<16}", " ".join(row))
with open("bots/fingerprints.py", "w", encoding="utf-8") as f:
    f.write('"""Generated by tools/rebuild_fp.py from ' + folder + ' replays: bet-size signatures and measured\n'
            'statistics (in our core\'s own counter definitions) of the final\'s opponents."""\n\n')
    f.write("FP_SIGNATURES = " + json.dumps(sig, sort_keys=True) + "\n\n")
    f.write("FP_PROFILES = " + json.dumps(prof, sort_keys=True) + "\n")
print("written bots/fingerprints.py")
