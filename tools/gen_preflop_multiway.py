"""
Generates poker_engine/preflop_multiway.py: Monte Carlo equity (pot share, ties split)
of each of the 169 canonical starting hands against 1..7 random opponents.

This mirrors what the Deep-ML SDK's state.preflop_equity() / preflop_rank() report
("table lookup of your hole cards against the players still in").

Usage: python tools/gen_preflop_multiway.py [samples_per_cell]
"""

from __future__ import annotations
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from poker_engine.evaluator import eval_7  # noqa: E402


def canonical_classes():
    """Yields (hi_rank, lo_rank, suited) for the 169 classes, ranks 0..12 (2..A)."""
    for hi in range(12, -1, -1):
        for lo in range(hi, -1, -1):
            if hi == lo:
                yield (hi, lo, False)
            else:
                yield (hi, lo, True)
                yield (hi, lo, False)


def main() -> None:
    samples = int(sys.argv[1]) if len(sys.argv) > 1 else 4000
    rng = random.Random(12345)
    classes = list(canonical_classes())
    table = {}
    for (hi, lo, suited) in classes:
        c0 = (hi << 2) | 0
        c1 = (lo << 2) | (0 if suited else 1)
        rest = [c for c in range(52) if c != c0 and c != c1]
        row = []
        for n_opp in range(1, 8):
            share = 0.0
            need = 5 + 2 * n_opp
            for _ in range(samples):
                d = rng.sample(rest, need)
                b0, b1, b2, b3, b4 = d[0], d[1], d[2], d[3], d[4]
                me = eval_7(c0, c1, b0, b1, b2, b3, b4)
                best = me
                ties = 1
                lost = False
                for k in range(n_opp):
                    v = eval_7(d[5 + 2 * k], d[6 + 2 * k], b0, b1, b2, b3, b4)
                    if v > me:
                        lost = True
                        break
                    if v == me:
                        ties += 1
                if not lost:
                    share += 1.0 / ties
                del best
            row.append(round(share / samples, 4))
        table[(hi, lo, suited)] = row
        print(f"{hi:2d} {lo:2d} {'s' if suited else 'o'} {row}", flush=True)

    out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                       "poker_engine", "preflop_multiway.py")
    with open(out, "w", encoding="utf-8") as f:
        f.write('"""Generated by tools/gen_preflop_multiway.py: equity of each canonical hand\n')
        f.write(f'vs 1..7 random opponents ({samples} Monte Carlo samples per cell)."""\n\n')
        f.write("# key: (hi_rank, lo_rank, suited) with ranks 0..12 = 2..A\n")
        f.write("# value: [eq_vs_1, eq_vs_2, ..., eq_vs_7]\n")
        f.write("MULTIWAY_EQ = {\n")
        for k, v in table.items():
            f.write(f"    {k!r}: {v!r},\n")
        f.write("}\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
